val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// DIST-6: release signing. The keys live outside the repository: a
// keystore.properties (storeFile, storePassword, keyAlias, keyPassword) at
// $MENGER_ANDROID_KEYSTORE_PROPERTIES, else gen/android/keystore.properties
// (gitignored). A relative storeFile is taken from the properties file's
// directory. With neither, the release build is unsigned.
val keystorePropertiesFile: File = providers.environmentVariable("MENGER_ANDROID_KEYSTORE_PROPERTIES")
    .orNull?.takeIf { it.isNotBlank() }?.let { File(it) }
    ?: rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val releaseSigned = keystoreProperties.getProperty("storeFile") != null

android {
    compileSdk = 37
    namespace = "ai.hypermemetic.menger"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "ai.hypermemetic.menger"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        if (releaseSigned) {
            create("release") {
                val store = File(keystoreProperties.getProperty("storeFile"))
                storeFile = if (store.isAbsolute) store else File(keystorePropertiesFile.parentFile, store.path)
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            if (releaseSigned) {
                signingConfig = signingConfigs.getByName("release")
            } else {
                logger.warn("menger-desktop: no keystore.properties ($keystorePropertiesFile) — the release build is unsigned")
            }
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

